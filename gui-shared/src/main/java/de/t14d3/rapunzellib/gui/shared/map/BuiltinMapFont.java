    @Override
    public int lineHeight() {
        return GLYPH_HEIGHT;
    }

    @Override
    public int charWidth(char ch) {
        return GLYPH_WIDTH;
    }

    @Nullable
    @Override
    public GuiMapGlyph glyph(char ch) {
        if (ch < FIRST_CHAR || ch > LAST_CHAR) {
            return null;
        }
        byte[] rows = GLYPHS[ch - FIRST_CHAR];
        boolean[] pixels = new boolean[GLYPH_WIDTH * GLYPH_HEIGHT];
        for (int row = 0; row < GLYPH_HEIGHT; row++) {
            for (int col = 0; col < GLYPH_WIDTH; col++) {
                pixels[row * GLYPH_WIDTH + col] = (rows[row] & (0x10 >> col)) != 0;
            }
        }
        return new GuiMapGlyph(GLYPH_WIDTH, GLYPH_HEIGHT, pixels);
    }

    @Override
    public @NotNull String toString() {
        return "BuiltinMapFont(5x7)";
    }
